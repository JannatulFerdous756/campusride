<?php
/* Shared installer functions (used by install.php and tools/cli-install.php). PHP 7.4+. */

function cr_pdo(string $host, int $port, string $name, string $user, string $pass, bool $createDb = false): PDO
{
    $opts = [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC, PDO::ATTR_EMULATE_PREPARES => false];
    if ($createDb) {
        $root = new PDO("mysql:host=$host;port=$port;charset=utf8mb4", $user, $pass, $opts);
        if (!preg_match('/^[A-Za-z0-9_]{1,64}$/', $name)) {
            throw new RuntimeException('Database name may only contain letters, numbers and underscore.');
        }
        $root->exec("CREATE DATABASE IF NOT EXISTS `$name` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
    }
    return new PDO("mysql:host=$host;port=$port;dbname=$name;charset=utf8mb4", $user, $pass, $opts);
}

function cr_run_schema(PDO $pdo): int
{
    $sql = file_get_contents(CR_ROOT . '/database/schema.sql');
    $sql = preg_replace('/^\s*--.*$/m', '', (string)$sql);
    $n = 0;
    foreach (explode(';', (string)$sql) as $stmt) {
        $stmt = trim($stmt);
        if ($stmt !== '') {
            $pdo->exec($stmt);
            $n++;
        }
    }
    return $n;
}

function cr_has_users(PDO $pdo): bool
{
    try {
        return (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn() > 0;
    } catch (PDOException $e) {
        return false;
    }
}

function cr_create_user(PDO $pdo, string $name, string $email, string $phone, string $hash, string $role, string $status = 'active'): int
{
    $st = $pdo->prepare('INSERT INTO users (name, email, phone, password_hash, role, status, created_at) VALUES (?,?,?,?,?,?,?)');
    $st->execute([$name, strtolower($email), $phone, $hash, $role, $status, date('Y-m-d H:i:s')]);
    return (int)$pdo->lastInsertId();
}

function cr_write_config(array $c): array
{
    $code = "<?php\n// CampusRide configuration - generated by the installer. Keep this file private (never commit it).\nreturn " . var_export($c, true) . ";\n";
    $path = cr_config_path();
    $ok = @file_put_contents($path, $code) !== false;
    if ($ok) {
        @chmod($path, 0640);
    }
    return ['ok' => $ok, 'path' => $path, 'code' => $code];
}

